#!/usr/bin/env node
/**
 * build-css.mjs — Joins the CSS source files into css/player-one.css so the page
 * makes one stylesheet request instead of thirteen.
 *
 *   node scripts/build-css.mjs          write css/player-one.css
 *   node scripts/build-css.mjs --check  fail if the bundle is out of date (used by npm test)
 *
 * Edit the source files in css/, never the bundle. The order below is the cascade order.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const CSS_SOURCES = [
  'tokens', 'base', 'components', 'shell', 'title', 'screens', 'skilltree',
  'book', 'badges', 'extras', 'summary', 'world', 'comfort',
];
const OUT = path.join(root, 'css', 'player-one.css');

const bundle = [
  '/* GENERATED by scripts/build-css.mjs from the other files in css/. Do not edit this file. */',
  ...CSS_SOURCES.map(name => `\n/* ===== ${name}.css ===== */\n${fs.readFileSync(path.join(root, 'css', `${name}.css`), 'utf8').trim()}\n`),
].join('\n');

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== bundle) {
    console.error('css/player-one.css is out of date. Run: npm run css');
    process.exit(1);
  }
  console.log('CSS bundle is up to date');
} else {
  fs.writeFileSync(OUT, bundle);
  console.log(`css/player-one.css written (${(bundle.length / 1024).toFixed(1)} KB)`);
}
